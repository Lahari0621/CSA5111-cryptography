void perm(B *o, B *i, B *t, int n)
{
    B x[64];

    for (int j = 0; j < n; j++)
        x[j] = i[t[j] - 1];

    memcpy(o, x, n);
}

void keys(B *k, B sk[16][48])
{
    B cd[56];

    perm(cd, k, PC1, 56);

    for (int r = 0; r < 16; r++)
    {
        for (int s = 0; s < SH[r]; s++)
        {
            B a = cd[0], b = cd[28];

            memmove(cd, cd + 1, 27);
            cd[27] = a;

            memmove(cd + 28, cd + 29, 27);
            cd[55] = b;
        }

        perm(sk[r], cd, PC2, 48);
    }
}

void des(B *in, B *out, B sk[16][48], int dec)
{
    B b[64], l[32], r[32], e[48], f[32], t[32];

    perm(b, in, IP, 64);

    memcpy(l, b, 32);
    memcpy(r, b + 32, 32);

    for (int i = 0; i < 16; i++)
    {
        B *k = sk[dec ? 15 - i : i];

        perm(e, r, E, 48);

        for (int j = 0; j < 48; j++)
            e[j] ^= k[j];

        for (int s = 0; s < 8; s++)
        {
            B *x = e + 6 * s;

            int v = S[s][(x[0] * 2 + x[5]) * 16 +
                          x[1] * 8 + x[2] * 4 +
                          x[3] * 2 + x[4]];

            for (int j = 0; j < 4; j++)
                f[4 * s + j] = (v >> (3 - j)) & 1;
        }

        perm(f, f, P, 32);

        for (int j = 0; j < 32; j++)
            t[j] = l[j] ^ f[j];

        memcpy(l, r, 32);
        memcpy(r, t, 32);
    }

    memcpy(b, r, 32);
    memcpy(b + 32, l, 32);

    perm(out, b, FP, 64);
}

void h2b(char *h, B *b)
{
    for (int i = 0; i < 64; i++)
    {
        int v = h[i / 4] >= 'A'
            ? h[i / 4] - 'A' + 10
            : h[i / 4] - '0';

        b[i] = (v >> (3 - i % 4)) & 1;
    }
}

